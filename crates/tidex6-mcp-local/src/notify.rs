//! Досылка хода работы в канал оператора.
//!
//! Платёж идёт полминуты, и человек не должен всё это время спрашивать «ну
//! как?». Он написал одну фразу — дальше сообщения приходят сами: принято,
//! перевод подтверждён, готово.
//!
//! **Почему сервер пишет в Telegram напрямую, а не через агента.** Инструмент
//! MCP отвечает один раз, на вызов. Всё, что происходит потом, ему сказать
//! нечем: у протокола есть уведомления о прогрессе, но дойдут ли они до чата —
//! зависит от клиента, а рассчитывать на это в демонстрации нельзя. Прямая
//! отправка тем же ботом выглядит для человека так же и не зависит ни от чего.
//!
//! Секция необязательная: без неё сервер работает ровно так же, только молча, и
//! состояние спрашивают через `payment_status`.

use serde::Deserialize;

/// Куда писать. Токен тот же, что у бота в ZeroClaw — сообщения приходят от
/// того же имени, которому человек уже пишет.
#[derive(Debug, Clone, Deserialize)]
pub struct Notify {
    pub bot_token: String,
    /// Идентификатор чата. У супергрупп он начинается с `-100`.
    pub chat_id: String,
}

impl Notify {
    /// Отправить строку в чат.
    ///
    /// Ошибки проглатываются намеренно: недоставленное уведомление — досадно,
    /// но это не повод обрушить платёж, который в этот момент идёт. Работа
    /// важнее рассказа о ней.
    pub fn say(&self, text: &str) {
        let url = format!(
            "https://api.telegram.org/bot{}/sendMessage",
            self.bot_token
        );
        let body = serde_json::json!({
            "chat_id": self.chat_id,
            "text": text,
            "disable_web_page_preview": true,
        });
        let client = match reqwest::blocking::Client::builder()
            .timeout(std::time::Duration::from_secs(10))
            .build()
        {
            Ok(c) => c,
            Err(_) => return,
        };
        let _ = client.post(&url).json(&body).send();
    }
}
