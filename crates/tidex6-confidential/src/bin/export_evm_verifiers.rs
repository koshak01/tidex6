//! Emit the EVM verifiers for the hidden-amount pool — Solidity and Stylus,
//! from one verifying key each, the way `export_solidity_verifier` does for
//! the fixed-denomination `WithdrawCircuit<20>`.
//!
//! Two circuits, two verifiers:
//!
//! - `WithdrawCircuit` (8 public inputs) — read from the ceremony state when
//!   one is given or found, otherwise the development setup. The public
//!   ceremony (ADR-017) runs on exactly this circuit, so the final state drops
//!   in here unchanged.
//! - `TransferCircuit` (4 public inputs, join-split) — development setup only
//!   for now; it joins the ceremony in the next cycle.
//!
//! Writes:
//!
//! ```text
//! contracts/src/Tidex6HiddenWithdrawVerifier.sol
//! contracts/src/Tidex6HiddenTransferVerifier.sol
//! stylus/hidden-withdraw-verifier/src/vk.rs
//! stylus/hidden-transfer-verifier/src/vk.rs
//! crates/tidex6-confidential/artifacts/hidden_withdraw_pk.bin
//! crates/tidex6-confidential/artifacts/hidden_transfer_pk.bin
//! ```
//!
//! The two `.bin` files are the matching proving keys, serialized the way the
//! browser prover reads them (`ProvingKey::serialize_uncompressed`). A verifier
//! and its proving key must come from the same setup, so they leave here
//! together. Copy them to `tidex6-web/static/wasm/` on deploy.
//!
//! Usage:
//!
//! ```text
//! cargo run --bin export_evm_verifiers --release [path/to/withdraw.state]
//! ```
//!
//! Without an argument it looks for `$HOME/.tidex6-ceremony/final.state`, then
//! for the checked-in genesis `crates/tidex6-confidential/ceremony/withdraw_genesis.state`,
//! and only then falls back to the seeded development setup. The generated
//! header says which one was used.

use std::fs;
use std::path::PathBuf;

use ark_bn254::Bn254;
use ark_groth16::{ProvingKey, VerifyingKey};
use ark_serialize::CanonicalSerialize;
use ark_std::rand::SeedableRng;
use ark_std::rand::rngs::StdRng;

use tidex6_circuits::ceremony::find_workspace_root;
use tidex6_circuits::evm_solidity::{render_solidity_verifier_named, render_stylus_vk};
use tidex6_circuits::mpc::CeremonyState;
use tidex6_confidential::ceremony::selftest_pk;
use tidex6_confidential::{transfer, withdraw};

/// Fixed self-test prover seed — a functional check of the key, not a
/// production proof, so a fixed seed keeps the run reproducible.
const SELFTEST_SEED: u64 = 0xce12_0517_beac_0f17;

/// Development setup seeds — the same ones `gen_vk` uses, so a dev-mode EVM
/// verifier matches the dev-mode Solana program byte for byte.
const WITHDRAW_SEED: u64 = 0x775f_6869_6464_656e; // "w_hidden"
const TRANSFER_SEED: u64 = 0x745f_6869_6464_656e; // "t_hidden"

const CEREMONY_HEADER: &str = "// DO NOT EDIT BY HAND. Generated by\n\
     // `crates/tidex6-confidential/src/bin/export_evm_verifiers.rs` from the\n\
     // public trusted-setup ceremony state (ADR-017) for the hidden-amount\n\
     // withdraw circuit (8 public inputs).\n\
     //\n\
     // Multi-party Phase-2 setup: secure as long as at least one contributor\n\
     // was honest and destroyed their randomness (1-of-N). Byte-reproducible —\n\
     // anyone who downloaded the CeremonyState can re-run this export and\n\
     // diff the result.\n\
     //\n\
     // The same verifying key backs the Solana program; see\n\
     // `programs/tidex6-confidential-pool/src/withdraw_vk.rs`.\n\n";

const GENESIS_HEADER: &str = "// DO NOT EDIT BY HAND. Generated by\n\
     // `crates/tidex6-confidential/src/bin/export_evm_verifiers.rs` from the\n\
     // ceremony GENESIS state of the hidden-amount withdraw circuit.\n\
     //\n\
     // ############################################################\n\
     // # GENESIS KEY — NO CONTRIBUTIONS APPLIED YET.              #\n\
     // # Its toxic waste is the Phase-1 tau of the public ptau,   #\n\
     // # so treat it as a development key: testnet only, no value #\n\
     // # behind this contract. Replaced by the finalized state.   #\n\
     // ############################################################\n\n";

const DEV_HEADER: &str = "// DO NOT EDIT BY HAND. Generated by\n\
     // `crates/tidex6-confidential/src/bin/export_evm_verifiers.rs`.\n\
     //\n\
     // ############################################################\n\
     // # DEVELOPMENT KEY — NOT FROM THE PUBLIC CEREMONY.          #\n\
     // # Derived from a seed in the public repository, so anyone  #\n\
     // # can forge proofs against it. Testnet only. Do not put    #\n\
     // # value behind this contract.                              #\n\
     // ############################################################\n\n";

/// Where the withdraw key comes from, in order of preference.
enum WithdrawSource {
    Ceremony(PathBuf),
    Genesis(PathBuf),
    Development,
}

/// Pick the withdraw key source: explicit argument, the finalized state in
/// `$HOME`, the checked-in genesis, then the development setup.
fn locate_withdraw_source(root: &std::path::Path) -> WithdrawSource {
    if let Some(argument) = std::env::args().nth(1) {
        return WithdrawSource::Ceremony(PathBuf::from(argument));
    }
    if let Ok(home) = std::env::var("HOME") {
        let final_state = PathBuf::from(format!("{home}/.tidex6-ceremony/final.state"));
        if final_state.exists() {
            return WithdrawSource::Ceremony(final_state);
        }
    }
    let genesis = root.join("crates/tidex6-confidential/ceremony/withdraw_genesis.state");
    if genesis.exists() {
        return WithdrawSource::Genesis(genesis);
    }
    WithdrawSource::Development
}

/// Load a ceremony state and prove that its key drives this circuit.
fn withdraw_key_from_state(path: &std::path::Path) -> (ProvingKey<Bn254>, VerifyingKey<Bn254>) {
    let bytes = fs::read(path).expect("read ceremony state");
    let state = CeremonyState::from_bytes(&bytes).expect("parse ceremony state");
    println!(
        "ceremony state: {} ({} contributions)",
        path.display(),
        state.contributions.len()
    );
    let vk = selftest_pk(&state.pk, SELFTEST_SEED).expect("ceremony pk self-test failed");
    println!("self-test OK — key encodes a working hidden-amount WithdrawCircuit");
    (state.pk, vk)
}

/// Write the proving key next to the verifier it belongs to.
fn write_proving_key(root: &std::path::Path, pk: &ProvingKey<Bn254>, name: &str) {
    let dir = root.join("crates/tidex6-confidential/artifacts");
    fs::create_dir_all(&dir).expect("create artifacts dir");
    let path = dir.join(format!("{name}_pk.bin"));
    let mut bytes = Vec::new();
    pk.serialize_uncompressed(&mut bytes).expect("serialize proving key");
    fs::write(&path, &bytes).expect("write proving key");
    println!("wrote {} ({} bytes)", path.display(), bytes.len());
}

/// Write one verifier pair: the Solidity contract and the Stylus `vk.rs`.
fn write_pair(
    root: &std::path::Path,
    vk: &VerifyingKey<Bn254>,
    header: &str,
    contract_name: &str,
    circuit_label: &str,
    stylus_crate: &str,
) {
    let public_inputs = vk.gamma_abc_g1.len() - 1;
    println!("{contract_name}: {public_inputs} public inputs");

    let solidity_path = root.join(format!("contracts/src/{contract_name}.sol"));
    let solidity = render_solidity_verifier_named(vk, header, contract_name, circuit_label);
    fs::write(&solidity_path, solidity.as_bytes()).expect("write Solidity verifier");
    println!("wrote {}", solidity_path.display());

    let stylus_dir = root.join(format!("stylus/{stylus_crate}/src"));
    fs::create_dir_all(&stylus_dir).expect("create stylus src dir");
    let stylus_path = stylus_dir.join("vk.rs");
    fs::write(&stylus_path, render_stylus_vk(vk, header).as_bytes()).expect("write vk.rs");
    println!("wrote {}", stylus_path.display());
}

fn main() {
    let root = find_workspace_root();

    let ((withdraw_pk, withdraw_vk), withdraw_header) = match locate_withdraw_source(&root) {
        WithdrawSource::Ceremony(path) => (withdraw_key_from_state(&path), CEREMONY_HEADER),
        WithdrawSource::Genesis(path) => (withdraw_key_from_state(&path), GENESIS_HEADER),
        WithdrawSource::Development => {
            println!("no ceremony state found — using the DEVELOPMENT setup");
            let mut rng = StdRng::seed_from_u64(WITHDRAW_SEED);
            (withdraw::setup(&mut rng).expect("withdraw dev setup"), DEV_HEADER)
        }
    };
    assert_eq!(
        withdraw_vk.gamma_abc_g1.len() - 1,
        withdraw::WITHDRAW_NR_PUBLIC_INPUTS,
        "withdraw key has the wrong number of public inputs"
    );
    write_pair(
        &root,
        &withdraw_vk,
        withdraw_header,
        "Tidex6HiddenWithdrawVerifier",
        "hidden-amount withdraw circuit",
        "hidden-withdraw-verifier",
    );
    write_proving_key(&root, &withdraw_pk, "hidden_withdraw");

    println!("transfer (join-split): DEVELOPMENT setup — not yet in the ceremony");
    let mut rng = StdRng::seed_from_u64(TRANSFER_SEED);
    let (transfer_pk, transfer_vk) = transfer::setup(&mut rng).expect("transfer dev setup");
    assert_eq!(
        transfer_vk.gamma_abc_g1.len() - 1,
        transfer::TRANSFER_NR_PUBLIC_INPUTS,
        "transfer key has the wrong number of public inputs"
    );
    write_pair(
        &root,
        &transfer_vk,
        DEV_HEADER,
        "Tidex6HiddenTransferVerifier",
        "hidden-amount join-split circuit",
        "hidden-transfer-verifier",
    );
    write_proving_key(&root, &transfer_pk, "hidden_transfer");
}
