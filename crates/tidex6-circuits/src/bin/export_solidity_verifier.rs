//! Emit a Solidity Groth16 verifier for `WithdrawCircuit<20>` — the EVM
//! counterpart of `ceremony_extract_vk`.
//!
//! Reads the same ceremony state the Solana verifier is built from, self-tests
//! that the proving key encodes a working withdraw circuit, and writes
//! `contracts/src/Tidex6Verifier.sol`. The verifying key is therefore identical
//! on both chains: one setup, one ceremony, two verifiers.
//!
//! Usage:
//!
//! ```text
//! cargo run --bin export_solidity_verifier --release [path/to/final.state]
//! ```
//!
//! Without an argument it falls back to `$HOME/.tidex6-ceremony/final.state`,
//! and if that does not exist it uses the development setup — in which case the
//! generated header says so, loudly.

use std::fs;
use std::path::PathBuf;

use tidex6_circuits::ceremony::{find_workspace_root, selftest_pk};
use tidex6_circuits::evm_solidity::render_solidity_verifier;
use tidex6_circuits::mpc::CeremonyState;
use tidex6_circuits::withdraw::{WITHDRAW_TREE_DEPTH, setup_withdraw_circuit};

use ark_std::rand::SeedableRng;
use ark_std::rand::rngs::StdRng;

/// Fixed self-test prover seed — a functional check of the setup, not a
/// production proof, so a fixed seed keeps the run reproducible.
const SELFTEST_SEED: u64 = 0xce12_0517_beac_0f17;

/// Seed of the development setup — the same one `gen_withdraw_vk` uses, so the
/// dev-mode Solidity verifier matches the dev-mode Solana verifier.
const DEV_SETUP_SEED: u64 = 0x7715_ef25_d061_3517;

/// Header for a key that came out of the finalized public ceremony.
const CEREMONY_HEADER: &str = "// DO NOT EDIT BY HAND. Generated by\n\
     // `crates/tidex6-circuits/src/bin/export_solidity_verifier.rs` from the\n\
     // FINALIZED public trusted-setup ceremony state (ADR-017).\n\
     //\n\
     // Multi-party Phase-2 setup: secure as long as at least one contributor\n\
     // was honest and destroyed their randomness (1-of-N). Byte-reproducible —\n\
     // anyone who downloaded the final CeremonyState can re-run this export and\n\
     // diff the result.\n\
     //\n\
     // The same verifying key backs the Solana verifier; see\n\
     // `programs/tidex6-verifier/src/withdraw_vk.rs`.\n\n";

/// Header for the development key. Deliberately unmissable.
const DEV_HEADER: &str = "// DO NOT EDIT BY HAND. Generated by\n\
     // `crates/tidex6-circuits/src/bin/export_solidity_verifier.rs`.\n\
     //\n\
     // ############################################################\n\
     // # DEVELOPMENT KEY — NOT FROM THE PUBLIC CEREMONY.          #\n\
     // # Derived from a seed in the public repository, so anyone  #\n\
     // # can forge proofs against it. Testnet only. Do not put    #\n\
     // # value behind this contract.                              #\n\
     // ############################################################\n\n";

/// Locate the ceremony state: explicit argument, then the default path.
/// Returns `None` when neither exists, which selects the development setup.
fn locate_ceremony_state() -> Option<PathBuf> {
    if let Some(argument) = std::env::args().nth(1) {
        return Some(PathBuf::from(argument));
    }
    let home = std::env::var("HOME").ok()?;
    let default_path = PathBuf::from(format!("{home}/.tidex6-ceremony/final.state"));
    default_path.exists().then_some(default_path)
}

fn main() {
    let (vk, header) = match locate_ceremony_state() {
        Some(path) => {
            println!("reading ceremony state: {}", path.display());
            let state = CeremonyState::from_bytes(&fs::read(&path).expect("read ceremony state"))
                .expect("parse CeremonyState");
            println!("contributions in state: {}", state.contributions.len());
            for contribution in &state.contributions {
                println!("  - {}", contribution.name);
            }

            println!("self-testing the proving key (prove + verify a withdraw)…");
            let vk = selftest_pk(&state.pk, SELFTEST_SEED).expect("ceremony pk self-test failed");
            println!("self-test OK — setup encodes a working WithdrawCircuit<20>");
            (vk, CEREMONY_HEADER)
        }
        None => {
            println!("no ceremony state found — falling back to the DEVELOPMENT setup");
            println!("  seed = 0x{DEV_SETUP_SEED:016x} (public, forgeable — testnet only)");
            let mut rng = StdRng::seed_from_u64(DEV_SETUP_SEED);
            let (_pk, vk) = setup_withdraw_circuit::<WITHDRAW_TREE_DEPTH, _>(&mut rng)
                .expect("development setup");
            (vk, DEV_HEADER)
        }
    };

    println!("public inputs: {}", vk.gamma_abc_g1.len() - 1);

    let source = render_solidity_verifier(&vk, header);

    let out_dir = find_workspace_root().join("contracts/src");
    fs::create_dir_all(&out_dir).expect("create contracts/src");
    let out_path = out_dir.join("Tidex6Verifier.sol");
    fs::write(&out_path, source.as_bytes()).expect("write Tidex6Verifier.sol");

    println!("wrote {} ({} bytes)", out_path.display(), source.len());
}
