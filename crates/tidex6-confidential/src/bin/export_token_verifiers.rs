//! Emit the EVM verifiers for the confidential token — one per circuit, from
//! one verifying key each, the way `export_evm_verifiers` does for the
//! hidden-amount pool.
//!
//! Five circuits, five verifiers (`token/mod.rs` documents what each proves):
//!
//! | circuit    | public inputs | what the contract learns |
//! |------------|---------------|--------------------------|
//! | `pubkey`   | 2             | the registered point is a valid key |
//! | `transfer` | 18            | a balance moved; no amount anywhere |
//! | `unwrap`   | 7             | an amount left for the open ERC-20 |
//! | `deposit`  | 11            | a balance became a pool note |
//! | `exit`     | 8             | a pool note became a balance |
//!
//! All five run on the DEVELOPMENT setup: the public ceremony (ADR-017) is
//! still open on the pool's withdraw circuit, and the token circuits join it
//! in the next cycle. Every emitted file says so in its header, and nothing
//! with value behind it may be deployed against these keys.
//!
//! Writes, for each circuit:
//!
//! ```text
//! contracts/src/Tidex6Token<Name>Verifier.sol
//! crates/tidex6-confidential/artifacts/token_<name>_pk.bin
//! ```
//!
//! Plus, once, the curve constants the token contract needs:
//!
//! ```text
//! contracts/src/BabyJubjubConstants.sol
//! ```
//!
//! Those are generated rather than typed because the contract has to agree
//! with the circuits on the curve and on both generators down to the last
//! digit. A mistyped `H` would not fail to compile — it would accept
//! ciphertexts nobody can decrypt.
//!
//! The `.bin` files are the matching proving keys in the layout the browser
//! prover reads (`ProvingKey::serialize_uncompressed`). A verifier and its
//! proving key must come from the same setup, so they leave here together;
//! copy the `.bin` files to `tidex6-web/static/wasm/` on deploy.
//!
//! Usage:
//!
//! ```text
//! cargo run --bin export_token_verifiers --release
//! ```

use std::fs;
use std::path::Path;

use ark_bn254::Bn254;
use ark_groth16::{ProvingKey, VerifyingKey};
use ark_serialize::CanonicalSerialize;
use ark_std::rand::SeedableRng;
use ark_std::rand::rngs::StdRng;

use ark_ed_on_bn254::{EdwardsConfig, Fq as BjjBase, Fr as BjjFr};
use ark_ff::PrimeField;

use tidex6_circuits::ceremony::find_workspace_root;
use tidex6_circuits::evm_solidity::render_solidity_verifier_named;
use tidex6_confidential::token::elgamal;
use tidex6_confidential::token::{deposit, exit, pubkey, transfer, unwrap};

/// Development setup seeds, one per circuit. Fixed so that a re-run produces
/// byte-identical verifiers and anyone can reproduce them from this file.
const PUBKEY_SEED: u64 = 0x745f_7075_626b_6579; // "t_pubkey"
const TRANSFER_SEED: u64 = 0x745f_7472_616e_7366; // "t_transf"
const UNWRAP_SEED: u64 = 0x745f_756e_7772_6170; // "t_unwrap"
const DEPOSIT_SEED: u64 = 0x745f_6465_706f_7369; // "t_deposi"
const EXIT_SEED: u64 = 0x745f_6578_6974_5f5f; // "t_exit__"

const DEV_HEADER: &str = "// DO NOT EDIT BY HAND. Generated by\n\
     // `crates/tidex6-confidential/src/bin/export_token_verifiers.rs`.\n\
     //\n\
     // ############################################################\n\
     // # DEVELOPMENT KEY — NOT FROM THE PUBLIC CEREMONY.          #\n\
     // # Derived from a seed in the public repository, so anyone  #\n\
     // # can forge proofs against it. Testnet only. Do not put    #\n\
     // # value behind this contract. The confidential-token       #\n\
     // # circuits join the ceremony in the next cycle; until then #\n\
     // # this key is a development key by construction.           #\n\
     // ############################################################\n\n";

/// One circuit's setup output plus the names its artifacts carry.
struct Emitted {
    /// Solidity contract identifier, also the `.sol` file stem.
    contract_name: &'static str,
    /// Human-readable circuit name for the `@title` line.
    circuit_label: &'static str,
    /// Stem of the proving-key file: `token_<file_stem>_pk.bin`.
    file_stem: &'static str,
    /// How many public inputs the circuit is declared to take.
    declared_inputs: usize,
}

/// Write one verifier and its proving key.
///
/// Both come from the same setup call, which is the point: a verifier deployed
/// against a proving key from a different setup rejects every proof, and the
/// failure looks like a bug in the circuit rather than a mismatched pair.
///
/// # Параметры
/// * `root` — workspace root, the paths below are relative to it
/// * `pk` — proving key from the setup
/// * `vk` — verifying key from the same setup
/// * `meta` — names and the declared public-input count
///
/// # Возвращает
/// * `()` — panics if the key does not match the circuit's declared inputs,
///   because shipping such a pair would fail only at verification time
fn emit(root: &Path, pk: &ProvingKey<Bn254>, vk: &VerifyingKey<Bn254>, meta: &Emitted) {
    let public_inputs = vk.gamma_abc_g1.len() - 1;
    assert_eq!(
        public_inputs, meta.declared_inputs,
        "{}: key has {} public inputs, circuit declares {}",
        meta.contract_name, public_inputs, meta.declared_inputs
    );

    let solidity_path = root.join(format!("contracts/src/{}.sol", meta.contract_name));
    let solidity =
        render_solidity_verifier_named(vk, DEV_HEADER, meta.contract_name, meta.circuit_label);
    fs::write(&solidity_path, solidity.as_bytes()).expect("write Solidity verifier");
    println!(
        "{}: {} public inputs → {}",
        meta.contract_name,
        public_inputs,
        solidity_path.display()
    );

    let dir = root.join("crates/tidex6-confidential/artifacts");
    fs::create_dir_all(&dir).expect("create artifacts dir");
    let pk_path = dir.join(format!("token_{}_pk.bin", meta.file_stem));
    let mut bytes = Vec::new();
    pk.serialize_uncompressed(&mut bytes)
        .expect("serialize proving key");
    fs::write(&pk_path, &bytes).expect("write proving key");
    println!("  proving key: {} ({} bytes)", pk_path.display(), bytes.len());
}

/// Decimal string of a field element, as Solidity constants want it.
fn decimal<F: PrimeField>(value: &F) -> String {
    value.into_bigint().to_string()
}

/// Emit the curve constants the token contract shares with the circuits.
///
/// Writes `a`, `d`, the base-field modulus, the scalar-field modulus and both
/// generators. `G` is the curve's own generator; `H` is derived by hashing
/// (`elgamal::generator_h`), so its discrete log over `G` is unknown — which is
/// what makes the commitments binding.
///
/// # Параметры
/// * `root` — workspace root
///
/// # Возвращает
/// * `()` — panics only if the file cannot be written
fn emit_curve_constants(root: &Path) {
    let g = elgamal::generator_g();
    let h = elgamal::generator_h();
    let a = <EdwardsConfig as ark_ec::twisted_edwards::TECurveConfig>::COEFF_A;
    let d = <EdwardsConfig as ark_ec::twisted_edwards::TECurveConfig>::COEFF_D;

    let body = format!(
        "// SPDX-License-Identifier: MIT\n\
         pragma solidity ^0.8.20;\n\n\
         {DEV_HEADER}\
         /// @title Baby Jubjub constants, generated from the circuit crate\n\
         /// @notice The curve the confidential-token ciphertexts live on:\n\
         ///         a twisted Edwards curve whose coordinates are elements of\n\
         ///         the BN254 scalar field. That is the whole reason it is\n\
         ///         used — inside a Groth16 circuit over BN254 its arithmetic\n\
         ///         is native, so a point addition costs units of constraints\n\
         ///         instead of hundreds of thousands.\n\
         ///\n\
         /// @dev Generated by `export_token_verifiers`. The contract and the\n\
         ///      circuits must agree on every digit here: a wrong `H` still\n\
         ///      compiles and still verifies, and produces balances whose\n\
         ///      owner cannot decrypt them.\n\
         library BabyJubjubConstants {{\n\
         \x20   /// Base field of the curve = scalar field of BN254.\n\
         \x20   uint256 internal constant P =\n\
         \x20       {p};\n\n\
         \x20   /// Order of the prime-order subgroup: valid secret scalars are below it.\n\
         \x20   uint256 internal constant L =\n\
         \x20       {l};\n\n\
         \x20   /// Curve coefficient `a` of `a*x^2 + y^2 = 1 + d*x^2*y^2`.\n\
         \x20   uint256 internal constant A = {a};\n\n\
         \x20   /// Curve coefficient `d`.\n\
         \x20   uint256 internal constant D = {d};\n\n\
         \x20   /// Generator `G`: amounts are committed as `m*G`.\n\
         \x20   uint256 internal constant GX =\n\
         \x20       {gx};\n\
         \x20   uint256 internal constant GY =\n\
         \x20       {gy};\n\n\
         \x20   /// Second generator `H`, hash-derived: blinding is `r*H`, and a\n\
         \x20   /// public key is `s^-1 * H`.\n\
         \x20   uint256 internal constant HX =\n\
         \x20       {hx};\n\
         \x20   uint256 internal constant HY =\n\
         \x20       {hy};\n\
         }}\n",
        p = BjjBase::MODULUS,
        l = BjjFr::MODULUS,
        a = decimal(&a),
        d = decimal(&d),
        gx = decimal(&g.x),
        gy = decimal(&g.y),
        hx = decimal(&h.x),
        hy = decimal(&h.y),
    );
    let path = root.join("contracts/src/BabyJubjubConstants.sol");
    fs::write(&path, body.as_bytes()).expect("write curve constants");
    println!("wrote {}", path.display());
}

fn main() {
    let root = find_workspace_root();
    println!("confidential token: DEVELOPMENT setup for all five circuits");
    emit_curve_constants(&root);

    let mut rng = StdRng::seed_from_u64(PUBKEY_SEED);
    let (pk, vk) = pubkey::setup(&mut rng).expect("pubkey setup");
    emit(
        &root,
        &pk,
        &vk,
        &Emitted {
            contract_name: "Tidex6TokenPubkeyVerifier",
            circuit_label: "confidential-token public-key validity circuit",
            file_stem: "pubkey",
            declared_inputs: pubkey::PUBKEY_NR_PUBLIC_INPUTS,
        },
    );

    let mut rng = StdRng::seed_from_u64(TRANSFER_SEED);
    let (pk, vk) = transfer::setup(&mut rng).expect("token transfer setup");
    emit(
        &root,
        &pk,
        &vk,
        &Emitted {
            contract_name: "Tidex6TokenTransferVerifier",
            circuit_label: "confidential-token transfer circuit",
            file_stem: "transfer",
            declared_inputs: transfer::TRANSFER_NR_PUBLIC_INPUTS,
        },
    );

    let mut rng = StdRng::seed_from_u64(UNWRAP_SEED);
    let (pk, vk) = unwrap::setup(&mut rng).expect("token unwrap setup");
    emit(
        &root,
        &pk,
        &vk,
        &Emitted {
            contract_name: "Tidex6TokenUnwrapVerifier",
            circuit_label: "confidential-token unwrap circuit",
            file_stem: "unwrap",
            declared_inputs: unwrap::UNWRAP_NR_PUBLIC_INPUTS,
        },
    );

    let mut rng = StdRng::seed_from_u64(DEPOSIT_SEED);
    let (pk, vk) = deposit::setup(&mut rng).expect("token deposit setup");
    emit(
        &root,
        &pk,
        &vk,
        &Emitted {
            contract_name: "Tidex6TokenDepositVerifier",
            circuit_label: "confidential-token deposit-to-pool circuit",
            file_stem: "deposit",
            declared_inputs: deposit::DEPOSIT_NR_PUBLIC_INPUTS,
        },
    );

    let mut rng = StdRng::seed_from_u64(EXIT_SEED);
    let (pk, vk) = exit::setup(&mut rng).expect("token exit setup");
    emit(
        &root,
        &pk,
        &vk,
        &Emitted {
            contract_name: "Tidex6TokenExitVerifier",
            circuit_label: "confidential-token pool-exit circuit",
            file_stem: "exit",
            declared_inputs: exit::EXIT_NR_PUBLIC_INPUTS,
        },
    );
}
