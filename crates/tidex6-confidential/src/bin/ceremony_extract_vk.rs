//! Extract the verifying key from a **finalized** ceremony for the
//! hidden-amount withdraw circuit and write it into the pool program.
//!
//! Mirror of `tidex6-circuits/src/bin/ceremony_extract_vk.rs`, but for the
//! second circuit: the self-test here builds a three-element commitment and
//! eight public inputs, and the output goes to `programs/tidex6-confidential-pool/`.
//! A single binary with a circuit flag would be the place where one day the
//! key of one circuit gets extracted into the program of the other — and that
//! compiles, deploys, and silently rejects every proof.
//!
//! Run: cargo run -p tidex6-confidential --bin ceremony_extract_vk [-- <final.state>]
//! Defaults to `~/.tidex6-ceremony/final.state`.

use std::fs;

use tidex6_circuits::ceremony::{find_workspace_root, render_vk_source};
use tidex6_circuits::mpc::CeremonyState;
use tidex6_circuits::solana_bytes::{Groth16SolanaBytes, groth16_to_solana_bytes};
use tidex6_confidential::ceremony::selftest_pk;
use tidex6_confidential::withdraw::WITHDRAW_NR_PUBLIC_INPUTS;

/// Fixed self-test seed: this is a functional check of the setup, not a
/// production proof, and reproducibility matters more than randomness here.
const SELFTEST_SEED: u64 = 0xc0f1_dea1_0a30_0f17;

/// Header of the generated `withdraw_vk.rs` — records the multi-party origin
/// of the key, as opposed to the dev generator.
const CEREMONY_HEADER: &str = r#"//! Hardcoded verifying key for the hidden-amount `WithdrawCircuit` (8 public inputs).
//!
//! **DO NOT EDIT BY HAND.** Generated by
//! `crates/tidex6-confidential/src/bin/ceremony_extract_vk.rs` from the FINALIZED
//! public trusted-setup ceremony state (`~/.tidex6-ceremony/final.state`,
//! ADR-017). Byte-reproducible: anyone who downloaded the final `CeremonyState`
//! can re-run the extract and diff this file.
//!
//! Multi-party Phase-2 setup — secure as long as at least one contributor was
//! honest and destroyed their randomness (1-of-N). The final contribution is a
//! public drand beacon (see `final.json`).
"#;

fn main() {
    let home = std::env::var("HOME").expect("HOME");
    let default_path = format!("{home}/.tidex6-ceremony/final.state");
    let state_path = std::env::args().nth(1).unwrap_or(default_path);
    println!("reading ceremony state: {state_path}");

    let state = CeremonyState::from_bytes(&fs::read(&state_path).expect("read ceremony state"))
        .expect("parse CeremonyState");
    println!("contributions in state: {}", state.contributions.len());
    for c in &state.contributions {
        println!("  - {}", c.name);
    }

    println!("self-testing the proving key (prove + verify a hidden-amount withdraw)…");
    let vk = selftest_pk(&state.pk, SELFTEST_SEED).expect("ceremony pk self-test failed");
    println!("self-test OK — setup encodes a working hidden-amount WithdrawCircuit");

    // `groth16_to_solana_bytes` wants a proof (it negates `proof_a`); we only
    // need the VK fields, so pass a throwaway.
    let dummy_proof = ark_groth16::Proof::<ark_bn254::Bn254> {
        a: vk.alpha_g1,
        b: vk.beta_g2,
        c: vk.alpha_g1,
    };
    let bytes: Groth16SolanaBytes =
        groth16_to_solana_bytes(&dummy_proof, &vk).expect("groth16_to_solana_bytes");
    let nr_public = bytes.vk_ic.len() - 1;
    println!("  vk_ic length    = {}", bytes.vk_ic.len());
    println!("  nr_public_input = {nr_public}");
    // The public-input count is the only byte-level difference between the two
    // circuits' keys. Check it here rather than hope the program's compiler does.
    assert_eq!(
        nr_public, WITHDRAW_NR_PUBLIC_INPUTS,
        "this ceremony state belongs to a different circuit: expected {WITHDRAW_NR_PUBLIC_INPUTS} public inputs"
    );

    let out_path =
        find_workspace_root().join("programs/tidex6-confidential-pool/src/withdraw_vk.rs");
    let source = render_vk_source(&bytes, CEREMONY_HEADER);
    fs::write(&out_path, source).expect("write withdraw_vk.rs");
    println!("wrote {}", out_path.display());

    let fmt = std::process::Command::new("rustfmt")
        .arg(&out_path)
        .status()
        .expect("spawn rustfmt; is it on PATH?");
    if !fmt.success() {
        panic!("rustfmt failed on {}", out_path.display());
    }
    println!("formatted via rustfmt");
    println!("done — deploy the confidential pool carrying this VK");
}
