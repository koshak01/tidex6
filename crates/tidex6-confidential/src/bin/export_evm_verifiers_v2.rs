//! Emit the EVM verifiers of the v2 circuits (ADR-022) — Solidity and Stylus.
//!
//! Development setup for now, from the same seeds `gen_vk` uses, so the EVM
//! verifiers and the Solana program check one key. The v2 ceremony replaces
//! both keys before any mainnet deployment.
//!
//! Writes only v2 files — the v1 verifiers stand behind deployed pools and
//! are left alone:
//!
//! ```text
//! contracts/src/Tidex6HiddenWithdrawVerifierV2.sol
//! contracts/src/Tidex6HiddenTransferVerifierV2.sol
//! stylus/hidden-withdraw-verifier-v2/src/vk.rs
//! stylus/hidden-transfer-verifier-v2/src/vk.rs
//! crates/tidex6-confidential/artifacts/withdraw_v2_pk.bin
//! crates/tidex6-confidential/artifacts/transfer_v2_pk.bin
//! ```
//!
//! Usage: `cargo run --bin export_evm_verifiers_v2 --release`

use std::fs;

use ark_bn254::Bn254;
use ark_groth16::VerifyingKey;
use ark_serialize::CanonicalSerialize;
use ark_std::rand::SeedableRng;
use ark_std::rand::rngs::StdRng;

use tidex6_circuits::ceremony::find_workspace_root;
use tidex6_circuits::evm_solidity::{render_solidity_verifier_named, render_stylus_vk};
use tidex6_confidential::{transfer_v2, withdraw, withdraw_v2};

/// The seeds `gen_vk` uses for v2.
const WITHDRAW_V2_SEED: u64 = 0x775f_6869_6464_7632; // "w_hiddv2"
const TRANSFER_V2_SEED: u64 = 0x745f_6869_6464_7632; // "t_hiddv2"

const DEV_HEADER: &str = "// DO NOT EDIT BY HAND. Generated by\n\
     // `crates/tidex6-confidential/src/bin/export_evm_verifiers_v2.rs`.\n\
     //\n\
     // ############################################################\n\
     // # DEVELOPMENT KEY (ADR-022 v2 circuits). Single-contributor  #\n\
     // # seeded setup: whoever knows the seed can forge proofs.     #\n\
     // # Testnet only until the v2 ceremony replaces it.            #\n\
     // ############################################################\n\n";

fn write_pair(vk: &VerifyingKey<Bn254>, contract: &str, label: &str, stylus_crate: &str) {
    let root = find_workspace_root();
    let solidity = root.join(format!("contracts/src/{contract}.sol"));
    fs::write(
        &solidity,
        render_solidity_verifier_named(vk, DEV_HEADER, contract, label),
    )
    .expect("write Solidity verifier");
    println!(
        "wrote {} ({} public inputs)",
        solidity.display(),
        vk.gamma_abc_g1.len() - 1
    );
    let stylus = root.join(format!("stylus/{stylus_crate}/src/vk.rs"));
    fs::write(&stylus, render_stylus_vk(vk, DEV_HEADER)).expect("write vk.rs");
    println!("wrote {}", stylus.display());
}

fn write_pk(pk: &ark_groth16::ProvingKey<Bn254>, name: &str) {
    let path = find_workspace_root().join(format!(
        "crates/tidex6-confidential/artifacts/{name}_pk.bin"
    ));
    let mut bytes = Vec::new();
    pk.serialize_uncompressed(&mut bytes)
        .expect("serialize proving key");
    fs::write(&path, &bytes).expect("write proving key");
    println!("wrote {} ({} bytes)", path.display(), bytes.len());
}

fn main() {
    let mut rng = StdRng::seed_from_u64(WITHDRAW_V2_SEED);
    let (pk, vk) = withdraw_v2::setup(&mut rng).expect("withdraw_v2 setup");
    assert_eq!(
        vk.gamma_abc_g1.len() - 1,
        withdraw::WITHDRAW_NR_PUBLIC_INPUTS
    );
    write_pair(
        &vk,
        "Tidex6HiddenWithdrawVerifierV2",
        "v2 withdraw circuit",
        "hidden-withdraw-verifier-v2",
    );
    write_pk(&pk, "withdraw_v2");

    let mut rng = StdRng::seed_from_u64(TRANSFER_V2_SEED);
    let (pk, vk) = transfer_v2::setup(&mut rng).expect("transfer_v2 setup");
    assert_eq!(
        vk.gamma_abc_g1.len() - 1,
        transfer_v2::TRANSFER_V2_NR_PUBLIC_INPUTS
    );
    write_pair(
        &vk,
        "Tidex6HiddenTransferVerifierV2",
        "v2 in-pool transfer circuit",
        "hidden-transfer-verifier-v2",
    );
    write_pk(&pk, "transfer_v2");
}
