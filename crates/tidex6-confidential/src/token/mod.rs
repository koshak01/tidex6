//! Конфиденциальный токен: балансы как шифротексты twisted ElGamal на Baby
//! Jubjub, переводы с доказательствами Groth16 (ADR-015, ветка «токен»;
//! разбор — `docs/evm/HIDDEN_AMOUNTS_DESIGN_SPACE.md` §5–6).
//!
//! Почему Baby Jubjub: её координаты лежат в скалярном поле BN254, то есть
//! ровно в поле наших схем. Сложение и умножение точек внутри Groth16 стоят
//! единицы и тысячи ограничений; на BN254 G1 то же самое стоило бы сотни
//! тысяч (арифметика чужого поля). Контракт складывает точки Baby Jubjub сам.
//!
//! Шифр (как в Token-2022, только кривая другая): ключ `P = s⁻¹·H`;
//! шифротекст суммы `m` с открытием `r` — коммитмент `C = m·G + r·H` и ручка
//! `D = r·P`. Расшифровка `C − s·D = m·G`. Коммитмент общий, ручек столько,
//! сколько читателей: отправитель (чтобы контракт списал с его баланса),
//! получатель, аудитор. Все три расшифровывают одну и ту же точку, поэтому
//! равенства между ними доказывать не нужно — они следуют из конструкции.
//!
//! Сумму получатель читает не дискретным логарифмом, а из конверта: там едет
//! открытие `(m, r)`, и `C == m·G + r·H` проверяется одним сложением.
//! Дискретный лог остаётся аварийным путём ([`elgamal::decode_amount`]).
//!
//! Схемы:
//! - [`pubkey`] — ключ корректен (`s·P == H`), нужна при регистрации: точка,
//!   зарегистрированная без доказательства, могла бы лежать вне подгруппы.
//! - [`transfer`] — перевод между балансами: знание ключа, расшифровка
//!   баланса, диапазон остатка и суммы, корректность коммитмента и ручек.

