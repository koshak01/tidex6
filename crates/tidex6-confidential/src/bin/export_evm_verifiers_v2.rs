//! Emit every consumer of the v2 keys (ADR-022) from ceremony states.
//!
//! The keys come only from a ceremony state: the snarkjs genesis (zero
//! contributions) while v2 runs on testnets, the finalized state after the
//! public ceremony. There is no seeded fallback — an arkworks setup has a
//! different layout from the snarkjs keys the clients prove with, and a pool
//! carrying it rejects every withdraw.
//!
//! Each state is self-tested (a real note proved and verified) before anything
//! is written. Outputs, all from the same two keys:
//!
//! ```text
//! contracts/src/Tidex6HiddenWithdrawVerifierV2.sol
//! contracts/src/Tidex6HiddenTransferVerifierV2.sol
//! stylus/hidden-withdraw-verifier-v2/src/vk.rs
//! stylus/hidden-transfer-verifier-v2/src/vk.rs
//! programs/tidex6-pool-v2/src/withdraw_vk.rs
//! programs/tidex6-pool-v2/src/transfer_vk.rs
//! crates/tidex6-confidential/artifacts/withdraw_v2_pk.bin
//! crates/tidex6-confidential/artifacts/transfer_v2_pk.bin
//! ```
//!
//! Usage: `cargo run --release --bin export_evm_verifiers_v2 [-- <withdraw> <transfer>]`
//! Each argument is a ceremony state or a snarkjs `.zkey` (zero contributions);
//! a zkey is first turned into the committed genesis state. Without arguments
//! the committed geneses in `crates/tidex6-confidential/ceremony/` are used.

use std::fs::{self, File};
use std::io::BufReader;
use std::path::{Path, PathBuf};

use ark_bn254::Bn254;
use ark_groth16::{ProvingKey, VerifyingKey};
use ark_serialize::CanonicalSerialize;

use tidex6_circuits::ceremony::find_workspace_root;
use tidex6_circuits::evm_solidity::{render_solidity_verifier_named, render_stylus_vk};
use tidex6_circuits::mpc::CeremonyState;
use tidex6_circuits::solana_bytes::groth16_to_solana_bytes;
use tidex6_circuits::zkey::read_zkey_pk;
use tidex6_confidential::ceremony::SelftestError;
use tidex6_confidential::ceremony_v2::{
    render_program_vk, selftest_transfer_v2, selftest_withdraw_v2,
};
use tidex6_confidential::{transfer_v2, withdraw};

/// Fixed self-test prover seed: a functional check, reproducible on purpose.
const SELFTEST_SEED: u64 = 0xc0f1_dea1_0a30_0f22;

/// One v2 circuit: where its state lives and what its outputs are called.
struct Circuit {
    genesis: &'static str,
    selftest: fn(&ProvingKey<Bn254>, u64) -> Result<VerifyingKey<Bn254>, SelftestError>,
    public_inputs: usize,
    contract: &'static str,
    label: &'static str,
    stylus_crate: &'static str,
    program_file: &'static str,
    program_prefix: &'static str,
    pk_name: &'static str,
}

const CIRCUITS: [Circuit; 2] = [
    Circuit {
        genesis: "crates/tidex6-confidential/ceremony/withdraw_v2_genesis.state",
        selftest: selftest_withdraw_v2,
        public_inputs: withdraw::WITHDRAW_NR_PUBLIC_INPUTS,
        contract: "Tidex6HiddenWithdrawVerifierV2",
        label: "v2 withdraw circuit",
        stylus_crate: "hidden-withdraw-verifier-v2",
        program_file: "withdraw_vk.rs",
        program_prefix: "WITHDRAW_V2",
        pk_name: "withdraw_v2",
    },
    Circuit {
        genesis: "crates/tidex6-confidential/ceremony/transfer_v2_genesis.state",
        selftest: selftest_transfer_v2,
        public_inputs: transfer_v2::TRANSFER_V2_NR_PUBLIC_INPUTS,
        contract: "Tidex6HiddenTransferVerifierV2",
        label: "v2 in-pool transfer circuit",
        stylus_crate: "hidden-transfer-verifier-v2",
        program_file: "transfer_vk.rs",
        program_prefix: "TRANSFER_V2",
        pk_name: "transfer_v2",
    },
];

/// Header of every generated file: which state, how many contributions.
fn header(state: &Path, contributions: usize) -> String {
    let status = if contributions == 0 {
        "GENESIS KEY (zero contributions): anyone can forge proofs.\n\
         // Testnet only until the public v2 ceremony finalizes it."
    } else {
        "Multi-party key: sound while one contributor destroyed their\n\
         // randomness (1-of-N)."
    };
    format!(
        "// DO NOT EDIT BY HAND. Generated by\n\
         // `crates/tidex6-confidential/src/bin/export_evm_verifiers_v2.rs`\n\
         // from `{}` ({contributions} contributions).\n\
         // {status}\n\n",
        state.file_name().unwrap_or_default().to_string_lossy()
    )
}

fn export(root: &Path, circuit: &Circuit, state_path: &Path) {
    let state = CeremonyState::from_bytes(&fs::read(state_path).expect("read ceremony state"))
        .expect("parse ceremony state");
    let contributions = state.contributions.len();
    println!("{}: {contributions} contributions", state_path.display());
    let vk = (circuit.selftest)(&state.pk, SELFTEST_SEED).expect("self-test failed");
    assert_eq!(
        vk.gamma_abc_g1.len() - 1,
        circuit.public_inputs,
        "{} belongs to another circuit",
        state_path.display()
    );
    println!("self-test OK: {}", circuit.label);

    let rs_header = header(state_path, contributions);
    let solidity = root.join(format!("contracts/src/{}.sol", circuit.contract));
    let source = render_solidity_verifier_named(&vk, &rs_header, circuit.contract, circuit.label);
    fs::write(&solidity, source).expect("write Solidity verifier");
    println!("wrote {}", solidity.display());

    let stylus = root.join(format!("stylus/{}/src/vk.rs", circuit.stylus_crate));
    fs::write(&stylus, render_stylus_vk(&vk, &rs_header)).expect("write Stylus vk.rs");
    println!("wrote {}", stylus.display());

    write_program_vk(root, circuit, &vk, &rs_header.replace("// ", "//! "));
    write_pk(root, &state.pk, circuit.pk_name);
}

/// The Solana pool-v2 program's `<name>_vk.rs`, formatted.
fn write_program_vk(root: &Path, circuit: &Circuit, vk: &VerifyingKey<Bn254>, header: &str) {
    // `groth16_to_solana_bytes` negates `proof_a`; only the VK fields are used.
    let dummy = ark_groth16::Proof::<Bn254> {
        a: vk.alpha_g1,
        b: vk.beta_g2,
        c: vk.alpha_g1,
    };
    let bytes = groth16_to_solana_bytes(&dummy, vk).expect("groth16_to_solana_bytes");
    let path = root.join(format!(
        "programs/tidex6-pool-v2/src/{}",
        circuit.program_file
    ));
    fs::write(
        &path,
        render_program_vk(circuit.program_prefix, header, &bytes),
    )
    .expect("write program vk");
    let formatted = std::process::Command::new("rustfmt")
        .arg("--edition=2021")
        .arg(&path)
        .status()
        .expect("spawn rustfmt");
    assert!(formatted.success(), "rustfmt failed on {}", path.display());
    println!("wrote {}", path.display());
}

fn write_pk(root: &Path, pk: &ProvingKey<Bn254>, name: &str) {
    let path = root.join(format!(
        "crates/tidex6-confidential/artifacts/{name}_pk.bin"
    ));
    let mut bytes = Vec::new();
    pk.serialize_uncompressed(&mut bytes)
        .expect("serialize proving key");
    fs::write(&path, &bytes).expect("write proving key");
    println!("wrote {} ({} bytes)", path.display(), bytes.len());
}

fn main() {
    let root = find_workspace_root();
    let explicit: Vec<PathBuf> = std::env::args().skip(1).map(PathBuf::from).collect();
    assert!(
        explicit.is_empty() || explicit.len() == 2,
        "pass both states (withdraw, transfer) or none"
    );
    for (i, circuit) in CIRCUITS.iter().enumerate() {
        let state = explicit
            .get(i)
            .cloned()
            .unwrap_or_else(|| root.join(circuit.genesis));
        let state = if state.extension().is_some_and(|e| e == "zkey") {
            genesis_from_zkey(&root, circuit, &state)
        } else {
            state
        };
        export(&root, circuit, &state);
    }
}

/// Turn a snarkjs setup zkey into the committed genesis state of `circuit`.
fn genesis_from_zkey(root: &Path, circuit: &Circuit, zkey: &Path) -> PathBuf {
    let mut reader = BufReader::new(File::open(zkey).expect("open zkey"));
    let pk = read_zkey_pk(&mut reader).expect("read zkey");
    let out = root.join(circuit.genesis);
    fs::write(&out, CeremonyState::genesis(pk).to_bytes()).expect("write genesis state");
    println!("genesis {} from {}", out.display(), zkey.display());
    out
}
